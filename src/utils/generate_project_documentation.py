import os
import json
import datetime
import ast
import google.generativeai as genai

# Setup Gemini API
API_KEY = os.environ.get("GEMINI_API_KEY")
if not API_KEY:
    print("WARNING: GEMINI_API_KEY environment variable not set. Gemini API calls will fail. Set it via: export GEMINI_API_KEY='your_key'")
else:
    genai.configure(api_key=API_KEY)

# Initialize the Gemini model
# Recommended to use a fast, capable model for generating text.
model = genai.GenerativeModel('gemini-2.5-flash')

OUTPUT_FILE = "PROJECT_DETAILS.md"

def generate_academic_text(system_instruction, raw_data):
    """Sends raw data to Gemini to be formatted into an academic description."""
    if not API_KEY:
        return f"*(Gemini API missing. Showing raw data instead)*\n```text\n{raw_data}\n```"
    
    prompt = f"{system_instruction}\n\nRaw Data:\n```\n{raw_data}\n```\n\nPlease output ONLY the formatted markdown text, without conversational filler."
    
    try:
        response = model.generate_content(prompt)
        return response.text.strip()
    except Exception as e:
        return f"*(Error generating content via Gemini: {e})*\n\n```text\n{raw_data}\n```"

def append_to_doc(content):
    with open(OUTPUT_FILE, "a") as f:
        f.write(content + "\n\n")

def step_1_init():
    with open(OUTPUT_FILE, "w") as f:
        f.write(f"# Comprehensive Project Details: Bank SLM Benchmark\n")
        f.write(f"*Generated by AI on: {datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')}*\n\n")
        f.write("---\n\n")
    print("Step 1: Document initialized.")

def step_2_project_origin():
    append_to_doc("## 1. Project Origin & Status")
    try:
        with open("AGENTS.md", "r") as f:
            content = f.read().split("## Key Files")[0]
            instruction = "Rewrite the following project status and overview into a formal, academic introduction suitable for a thesis chapter on Domain-Specific Small Language Models."
            academic_text = generate_academic_text(instruction, content)
            append_to_doc(academic_text)
    except Exception as e:
        append_to_doc(f"*Could not process AGENTS.md: {e}*")
    print("Step 2 completed.")

def step_3_core_features():
    append_to_doc("## 2. Core Methodological Features")
    try:
        with open("README.md", "r") as f:
            lines = f.readlines()
            capture = False
            features = []
            for line in lines:
                if "## 🚀 Key Features" in line:
                    capture = True
                elif capture and line.startswith("## "):
                    break
                elif capture:
                    features.append(line)
            raw_features = "".join(features)
            instruction = "Take these bullet points describing software features and rewrite them as a cohesive, academic summary of the experimental capabilities of the research pipeline."
            academic_text = generate_academic_text(instruction, raw_features)
            append_to_doc(academic_text)
    except Exception as e:
        append_to_doc(f"*Could not process README.md: {e}*")
    print("Step 3 completed.")

def step_4_dir_structure():
    append_to_doc("## 3. High-Level Architecture (Directory Structure)")
    try:
        root_files = [f for f in os.listdir('.') if os.path.isfile(f) and not f.startswith('.')]
        data_files = os.listdir('data') if os.path.isdir('data') else []
        src_files = os.listdir('src') if os.path.isdir('src') else []
        
        raw_structure = f"Root Files: {root_files}\nData Folder: {data_files}\nSrc Folder: {src_files}"
        instruction = "Write a brief academic paragraph describing the physical architecture and modularity of the software repository based on these directory listings. Mention the separation of data, source code, and root configurations."
        academic_text = generate_academic_text(instruction, raw_structure)
        
        append_to_doc(academic_text)
    except Exception as e:
        append_to_doc(f"*Could not process directories: {e}*")
    print("Step 4 completed.")

def extract_json_schema(file_path):
    try:
        if file_path.endswith('.jsonl'):
            with open(file_path, 'r') as f:
                first_line = f.readline()
                data = json.loads(first_line)
                return list(data.keys())
        elif file_path.endswith('.json'):
            with open(file_path, 'r') as f:
                data = json.load(f)
                if isinstance(data, list) and len(data) > 0:
                    return list(data[0].keys())
                elif isinstance(data, dict):
                    return list(data.keys())
    except Exception:
        pass
    return []

def step_5_data_schema():
    append_to_doc("## 4. Dataset Taxonomy and Synthesis")
    try:
        schemas = {}
        for file in ['data/bank_queries.json', 'data/train_final_5500.jsonl', 'data/dpo_dataset.jsonl']:
            if os.path.exists(file):
                schemas[file] = extract_json_schema(file)
        
        raw_schemas = json.dumps(schemas, indent=2)
        instruction = "These are the JSON schemas extracted from the experimental datasets. Write an academic analysis explaining how the data is structured (e.g., query/reference pairs, SFT instruction data, DPO chosen/rejected formats) to train the SLMs."
        academic_text = generate_academic_text(instruction, raw_schemas)
        append_to_doc(academic_text)
    except Exception as e:
         append_to_doc(f"*Could not process schemas: {e}*")
    print("Step 5 completed.")

def extract_code_metadata(filepath):
    try:
        with open(filepath, 'r') as f:
            tree = ast.parse(f.read())
        docstring = ast.get_docstring(tree)
        funcs = [node.name for node in ast.walk(tree) if isinstance(node, ast.FunctionDef)]
        return {"docstring": docstring, "functions": funcs}
    except Exception:
        return None

def process_code_category(title, scripts):
    append_to_doc(f"### {title}")
    raw_code_data = ""
    for script in scripts:
        if os.path.exists(script):
            metadata = extract_code_metadata(script)
            if metadata:
                raw_code_data += f"\nFile: {script}\nDocstring: {metadata['docstring']}\nFunctions: {metadata['functions']}\n"
    
    if raw_code_data:
        instruction = f"Analyze this Python metadata (filenames, docstrings, and function names) for the {title} module. Write a detailed, academic breakdown of what this code does methodology-wise for the PhD thesis."
        academic_text = generate_academic_text(instruction, raw_code_data)
        append_to_doc(academic_text)
    else:
        append_to_doc("*No scripts found for this category.*")

def step_6_code_training():
    append_to_doc("## 5. Source Code Analysis")
    scripts = ['src/1_sft_train.py', 'src/2_dpo_train.py', 'src/3_orpo_train.py', 'src/6_multi_lora_merge.py', 'src/7_hyperparameter_sweep.py']
    process_code_category("Training and Alignment Subsystems", scripts)
    print("Step 6 completed.")

def step_7_code_eval():
    scripts = ['src/100_benchmark.py', 'src/99_evaluate.py']
    process_code_category("Inference and Deterministic Evaluation Framework", scripts)
    print("Step 7 completed.")

def step_8_code_utils():
    scripts = ['src/utils/generate_distillation_data.py', 'src/utils/generate_dpo_data.py', 'src/utils/generate_dataset.py', 'src/utils/augment_dataset.py']
    process_code_category("Data Engineering and Distillation Utilities", scripts)
    print("Step 8 completed.")

def step_9_pipeline_flow():
    append_to_doc("## 6. Pipeline Orchestration")
    try:
        with open("run_pipeline.sh", "r") as f:
            lines = f.readlines()
            key_commands = [line.strip() for line in lines if line.strip().startswith("python") or line.strip().startswith("./venv")]
            
        instruction = "These are the bash commands extracted from the main execution pipeline. Write a paragraph explaining the sequence of the methodology (e.g., how training leads to DPO, then benchmarking, then evaluation) to demonstrate scientific reproducibility."
        academic_text = generate_academic_text(instruction, "\n".join(key_commands))
        append_to_doc(academic_text)
    except Exception as e:
        append_to_doc(f"*Could not read run_pipeline.sh: {e}*")
    print("Step 9 completed.")

